export type MessageKey = keyof typeof messages.en;
type Variables = Record<string, string | number>;

type I18nValue = {
  locale: Locale;
  setLocale: (locale: Locale) => void;
  t: (key: MessageKey, variables?: Variables) => string;
  formatNumber: (value: number) => string;
  dateLocale: string;
};

const I18nContext = createContext<I18nValue | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocale] = useState<Locale>("en");
  const [ready, setReady] = useState(false);

  useEffect(() => {
    const timer = window.setTimeout(() => {
      const stored = window.localStorage.getItem("wellie.locale");
      if (stored === "en" || stored === "ja") setLocale(stored);
      setReady(true);
    }, 0);
    return () => window.clearTimeout(timer);
  }, []);

  useEffect(() => {
    if (!ready) return;
    window.localStorage.setItem("wellie.locale", locale);
    document.documentElement.lang = locale;
  }, [locale, ready]);

  const t = useCallback((key: MessageKey, variables?: Variables) => {
    let value: string = messages[locale][key];
    if (!variables) return value;
    for (const [name, replacement] of Object.entries(variables)) {
      value = value.replaceAll(`{${name}}`, String(replacement));
    }
    return value;
  }, [locale]);

  const value = useMemo<I18nValue>(() => ({
    locale,
    setLocale,
    t,
    formatNumber: (number) => number.toLocaleString(locale === "ja" ? "ja-JP" : "en"),
    dateLocale: locale === "ja" ? "ja-JP" : "en",
  }), [locale, t]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const value = useContext(I18nContext);
  if (!value) throw new Error("useI18n must be used inside I18nProvider");
  return value;
}
